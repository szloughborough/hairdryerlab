import io
import pandas as pd, numpy as np

bg = pd.read_pickle('analysis/brand_commission.pkl')   # 品牌级: 月销量/月销售额/加权均价
bg = bg[bg['月销量'] > 0].copy()
bg['当前佣金率'] = bg['品牌'].map({'Laifen': 0.15, 'slopehill': 0.20, 'dreame': 0.10}).fillna(0.04)
bg['当前单笔'] = (bg['加权均价'] * bg['当前佣金率']).round(2)
bg['当前月池'] = (bg['月销售额'] * bg['当前佣金率']).round(0)

out = []
def P(*a): out.append(' '.join(str(x) for x in a))

P("=" * 118)
P("佣金率提升的边际价值 —— 该去 Levanta 谈哪个产品？")
P("=" * 118)
P("逻辑：单笔佣金 = 加权均价 × 佣金率。月池 = 月销售额 × 佣金率。")
P("      提价空间 = 品牌当前(4%或自定义) → 若谈到更高速率的增量。")
P("")

rows = []
for _, r in bg.iterrows():
    row = {'品牌': r['品牌'], '月销量': int(r['月销量']), '月销售额': int(r['月销售额']),
           '加权均价': r['加权均价'], '当前佣金率': r['当前佣金率'],
           '当前单笔': r['当前单笔'], '当前月池': int(r['当前月池'])}
    for tgt in [0.08, 0.10, 0.15, 0.20]:
        row[f'@{int(tgt*100)}%月池'] = int(r['月销售额'] * tgt)
        row[f'@{int(tgt*100)}%增量'] = int(r['月销售额'] * tgt) - int(r['当前月池'])
    rows.append(row)
C = pd.DataFrame(rows)

# 排序：以谈到 15% 的增量排（一个现实的谈判目标）
C = C.sort_values('@15%增量', ascending=False)

P(f"{'品牌':<18}{'月销量':>8}{'月销售额':>12}{'均价':>8}{'现率':>7}{'现单笔':>8}{'现月池':>10}"
  f"{'@10%池':>10}{'@15%池':>10}{'@15%增量':>11}")
P("-" * 118)
for _, r in C.iterrows():
    P(f"{r['品牌']:<18}{r['月销量']:>8,}{r['月销售额']:>12,}{r['加权均价']:>8.2f}"
      f"{r['当前佣金率']:>7.0%}{r['当前单笔']:>8.2f}{r['当前月池']:>10,}"
      f"{r['@10%月池']:>10,}{r['@15%月池']:>10,}{r['@15%增量']:>11,}")
P("-" * 118)
P(f"{'合计':<18}{C['月销量'].sum():>8,}{C['月销售额'].sum():>12,}{'':>8}{'':>7}{'':>8}"
  f"{C['当前月池'].sum():>10,}{C['@10%月池'].sum():>10,}{C['@15%月池'].sum():>10,}"
  f"{C['@15%增量'].sum():>11,}")

P("\n" + "=" * 118)
P("★ 分层：哪些值得去谈")
P("=" * 118)

tier1 = C[(C['当前佣金率'] <= 0.04) & (C['@15%增量'] >= 5000)]
P("\n【第一层】当前 4%，且体量大 —— 谈判增量最可观")
for _, r in tier1.iterrows():
    P(f"  {r['品牌']:<16} 月销{r['月销量']:>6,}台  均价C${r['加权均价']:>7.2f}  "
      f"4%→15% 每月多赚 C${r['@15%增量']:>7,}  (单笔 C${r['加权均价']*0.15:.2f})")

tier2 = C[(C['当前佣金率'] > 0.04) & (C['当前佣金率'] < 0.20)]
P("\n【第二层】已有自定义佣金，但可能还能再谈")
for _, r in tier2.iterrows():
    P(f"  {r['品牌']:<16} 现{r['当前佣金率']:.0%} → 20% 每月多赚 C${r['@20%增量']:>7,}"
      f"  (现单笔 C${r['当前单笔']:.2f} → 20%单笔 C${r['加权均价']*0.20:.2f})")

tier3 = C[(C['当前佣金率'] <= 0.04) & (C['@15%增量'] < 5000) & (C['@15%增量'] > 500)]
P("\n【第三层】4% 但体量中小 —— 值得顺手问，优先级低")
for _, r in tier3.iterrows():
    P(f"  {r['品牌']:<16} 月销{r['月销量']:>6,}台  4%→15% 增 C${r['@15%增量']:>7,}/月")

P("\n" + "=" * 118)
P("★ 更关键的问题：对「单笔佣金」最敏感的是高均价品牌")
P("=" * 118)
P("低均价品牌即使谈到高佣金率，单笔仍然很低。看单笔佣金绝对值：")
C2 = C.copy()
C2['单笔@20%'] = (C2['加权均价'] * 0.20).round(2)
C2['单笔@15%'] = (C2['加权均价'] * 0.15).round(2)
C2 = C2.sort_values('单笔@20%', ascending=False)
P(f"\n{'品牌':<18}{'均价':>9}{'单笔@15%':>11}{'单笔@20%':>11}{'月销售额':>12}")
P("-" * 62)
for _, r in C2.head(14).iterrows():
    P(f"{r['品牌']:<18}{r['加权均价']:>9.2f}{r['单笔@15%']:>11.2f}{r['单笔@20%']:>11.2f}"
      f"{r['月销售额']:>12,}")

P("\n" + "=" * 118)
P("★ 优先级结论")
P("=" * 118)
P("1. Conair —— 月销 5,982 台、C$221,321 销售额，却只有 4% 佣金。")
P(f"   谈到 15% 则每月多赚 C${int(221321*0.11):,}。是投入产出比最高的一站。")
P("2. wavytalk —— 月销 3,092 台、C$130,850。C$42 均价、评分 4.3，与 slopehill 同价位带。")
P(f"   谈到 15% 增 C${int(130850*0.11):,}/月。")
P("3. Aina —— 月销 3,030 台但均价仅 C$25.99，单笔天花板低（20% 也只有 C$5.20）。")
P("   优先级降一档：它带来的是流量而非收入。")
P("4. Dyson / Shark / BabylissPro —— 均价 C$200-500，单笔佣金极高，")
P("   但 Dyson 几乎不可能给高佣金。若 Shark 能给 10-15%，单笔 C$20-30，非常值得。")
P("5. REVLON —— 月销 4,078 台但均价 C$20.89，单笔太低，只当流量词用。")

with io.open('analysis/_levanta_targets.txt', 'w', encoding='utf-8') as f:
    f.write('\n'.join(out))
C.to_pickle('analysis/levanta_targets.pkl')
print("written analysis/_levanta_targets.txt")
